export function buildPrompt(keys, desc) {
  const L = [];
  L.push('학습 앱에 넣을 구글 시트용 엑셀(.xlsx)을 만들어 줘. 첨부한 자료에서 데이터를 뽑아 아래 형식에 정확히 맞춰 줘.', '');
  L.push('[이번 자료 설명]', desc.trim() || '(자료 구조 설명)', '');
  L.push(`[결과물] 시트 ${keys.length}개가 든 .xlsx 하나. 탭 이름: ${keys.map((k) => `"${FORMATS[k].sheet}"`).join(', ')}`);
  L.push('- 헤더(첫 줄)는 넣지 말고 1행부터 데이터.', '- 칸(열) 순서는 아래 그대로.', '');
  keys.forEach((k) => {
    const f = FORMATS[k];
    L.push(`[${f.sheet} 탭] ${f.cols.length}칸 : ${f.cols.map(([c, d], i) => `(${i + 1})${c}${d ? ` ${d}` : ''}`).join(' ')}`);
    f.rules.forEach((r) => L.push(`- ${r}`));
    L.push('');
  });
  L.push('[공통 규칙]', '- 한자 · 훈음 · 해석을 지어내지 말고 자료에 있는 그대로.', '- 애매하거나 깨진 부분은 억지로 맞추지 말고 결과 맨 위에 검수 목록으로 알려 줄 것.', '', '다 만들면 .xlsx 파일로 받게 해 줘.');
  return L.join('\n');
}
